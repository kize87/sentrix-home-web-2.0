"""Generate UI labels from the versioned domain taxonomy; CI rejects drift."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from photobench.domain.datasets.qa_taxonomy import taxonomy_document

TARGET = Path(__file__).resolve().parents[1] / "apps/photobench/web/src/lib/qaTaxonomy.ts"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    value = taxonomy_document()
    text = "// Generated by scripts/export_qa_taxonomy.py. Edit the domain dictionary.\n"
    text += "export const qaTaxonomy = " + json.dumps(value, ensure_ascii=False, indent=2) + " as const;\n"
    text += """export const taxonomyLabels: Record<string, string> = {
  ...Object.fromEntries(Object.entries(qaTaxonomy.tasks).map(([key, task]) => [key, task.label])),
  ...Object.assign({}, ...Object.values(qaTaxonomy.tasks).map(task => task.subtypes)),
  ...qaTaxonomy.actions, ...qaTaxonomy.answerability, ...qaTaxonomy.difficulty, ...qaTaxonomy.special,
};
export const subtypeParent: Record<string, string> = Object.fromEntries(
  Object.entries(qaTaxonomy.tasks).flatMap(
    ([key, task]) => Object.keys(task.subtypes).map(sub => [sub, key])),
);
export const taxonomyLabel = (value: unknown) => taxonomyLabels[String(value)] || String(value || "未记录");
"""
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != text:
            print("QA taxonomy client is stale; run scripts/export_qa_taxonomy.py")
            return 1
        return 0
    TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
